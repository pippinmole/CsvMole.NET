using System.CodeDom.Compiler;
using CsvMole.SourceGenerators.Models;

namespace CsvMole.SourceGenerators.Emit;

internal static class ParserEmitter
{
    private static readonly string GeneratedCodeAttribute =
        $"[global::System.CodeDom.Compiler.GeneratedCode(\"CsvMole\", \"{typeof(ParserEmitter).Assembly.GetName().Version}\")]";

    public static string Emit(ParserModel parser)
    {
        using var text = new StringWriter();
        using var writer = new IndentedTextWriter(text, "    ");

        writer.WriteLine("// <auto-generated/>");
        writer.WriteLine("#nullable enable");
        writer.WriteLine();
        if (parser.Namespace is not null)
        {
            writer.WriteLine($"namespace {parser.Namespace};");
            writer.WriteLine();
        }

        foreach (var type in parser.ContainingTypes) OpenType(writer, type.Accessibility, type.Keyword, type.Name);
        OpenType(writer, parser.Accessibility, "class", parser.ClassName);

        for (var i = 0; i < parser.Methods.AsSpan().Length; i++)
        {
            if (i > 0) writer.WriteLine();
            EmitMethod(writer, parser.Methods[i]);
        }

        for (var depth = parser.ContainingTypes.AsSpan().Length; depth >= 0; depth--) CloseBlock(writer);

        writer.Flush();
        return text.ToString();
    }

    private static void EmitMethod(IndentedTextWriter writer, MethodModel method)
    {
        writer.WriteLine(GeneratedCodeAttribute);
        writer.WriteLine(method.Signature);
        writer.WriteLine("{");
        writer.Indent++;
        if (method.Model is null)
        {
            EmitStubBody(writer);
        }
        // Task 9: else EmitBody(writer, method, method.Model);
        CloseBlock(writer);
    }

    private static void EmitStubBody(IndentedTextWriter writer) =>
        writer.WriteLine("throw new global::System.NotSupportedException(\"CsvMole: see diagnostics\");");

    private static void OpenType(IndentedTextWriter writer, string accessibility, string keyword, string name)
    {
        writer.WriteLine(accessibility.Length == 0 ? $"partial {keyword} {name}" : $"{accessibility} partial {keyword} {name}");
        writer.WriteLine("{");
        writer.Indent++;
    }

    private static void CloseBlock(IndentedTextWriter writer)
    {
        writer.Indent--;
        writer.WriteLine("}");
    }
}
