using System.CodeDom.Compiler;
using System.Globalization;
using CsvMole.SourceGenerators.Models;
using Microsoft.CodeAnalysis.CSharp;

namespace CsvMole.SourceGenerators.Emit;

internal static class ParserEmitter
{
    private static readonly string GeneratedCodeAttribute =
        $"[global::System.CodeDom.Compiler.GeneratedCode(\"CsvMole\", \"{typeof(ParserEmitter).Assembly.GetName().Version}\")]";

    public static string Emit(ParserModel parser)
    {
        using var text = new StringWriter();
        using var writer = new IndentedTextWriter(text, "    ");

        writer.WriteLine("// <auto-generated/>");
        writer.WriteLine("#nullable enable");
        writer.WriteLine();
        if (parser.Namespace is not null)
        {
            writer.WriteLine($"namespace {parser.Namespace};");
            writer.WriteLine();
        }

        foreach (var type in parser.ContainingTypes) OpenType(writer, type.Accessibility, type.Keyword, type.Name);
        OpenType(writer, parser.Accessibility, "class", parser.ClassName);

        var names = new Names();
        for (var i = 0; i < parser.Methods.AsSpan().Length; i++)
        {
            if (i > 0) writer.WriteLine();
            EmitMethod(writer, parser.Methods[i], names);
        }

        foreach (var model in names.Models) EmitModelHelpers(writer, model, names);
        foreach (var converter in names.Converters)
        {
            writer.WriteLine();
            writer.WriteLine(GeneratedCodeAttribute);
            writer.WriteLine($"private static readonly {converter} {names.Converter(converter)} = new();");
        }
        if (names.UsesSpanParsable) EmitSpanParsableHelper(writer);

        for (var depth = parser.ContainingTypes.AsSpan().Length; depth >= 0; depth--) CloseBlock(writer);

        writer.Flush();
        return text.ToString();
    }

    private static void EmitMethod(IndentedTextWriter writer, MethodModel method, Names names)
    {
        writer.WriteLine(GeneratedCodeAttribute);
        var signature = method.Signature;
        if (method.IsAsync && method.Model is not null)
        {
            // Modifiers always include "partial", which must directly precede the return type, so async goes before it.
            var at = signature.IndexOf("partial ", StringComparison.Ordinal);
            if (at >= 0) signature = signature.Insert(at, "async ");
        }
        if (method.IsAsync && method.Model is not null && method.CancellationParamName is { } token)
        {
            // The token must be marked on the implementing part for WithCancellation(...) to reach it.
            var type = "global::System.Threading.CancellationToken " + Identifier(token);
            signature = signature.Replace(type, "[global::System.Runtime.CompilerServices.EnumeratorCancellation] " + type);
        }
        writer.WriteLine(signature);
        writer.WriteLine("{");
        writer.Indent++;
        if (method.Model is null) EmitStubBody(writer);
        else EmitBody(writer, method, method.Model, names.Model(method.Model));
        CloseBlock(writer);
    }

    private static void EmitStubBody(IndentedTextWriter writer) =>
        writer.WriteLine("throw new global::System.NotSupportedException(\"CsvMole: see diagnostics\");");

    private static void EmitBody(IndentedTextWriter w, MethodModel method, ModelInfo model, string id)
    {
        var a = method.IsAsync;
        string Read() => a ? $"await __r.ReadAsync({(method.CancellationParamName is { } t ? Identifier(t) : "default")}).ConfigureAwait(false)" : "__r.Read()";
        w.WriteLine(method.OptionsParamName is null
            ? "var __options = global::CsvMole.CsvOptions.Default;"
            : $"var __options = {Identifier(method.OptionsParamName)} ?? global::CsvMole.CsvOptions.Default;");
        w.WriteLine($"using var __r = new global::CsvMole.CsvReader({Identifier(method.ReaderParamName)}, __options, __options.Delimiter ?? {SymbolDisplay.FormatLiteral(model.Delimiter ?? ',', true)});");
        w.WriteLine("global::CsvMole.CsvColumnMap __map;");
        w.WriteLine("if (__options.HasHeader)");
        w.WriteLine("{");
        w.Indent++;
        w.WriteLine($"if (!{Read()}) yield break;");
        w.WriteLine($"__map = global::CsvMole.CsvHeader.Resolve(__r, __names_{id}, __orders_{id}, __members_{id});");
        CloseBlock(w);
        w.WriteLine("else");
        w.WriteLine("{");
        w.Indent++;
        w.WriteLine($"__map = global::CsvMole.CsvHeader.Resolve(null, __names_{id}, __orders_{id}, __members_{id});");
        CloseBlock(w);
        w.WriteLine($"while ({Read()})");
        w.WriteLine("{");
        w.Indent++;
        if (a) w.WriteLine($"{(method.CancellationParamName is { } ct ? Identifier(ct) : "default(global::System.Threading.CancellationToken)")}.ThrowIfCancellationRequested();");
        w.WriteLine($"if (__TryBind_{id}(__r, __map, out var __m)) yield return __m;");
        CloseBlock(w);
    }

    private static void EmitModelHelpers(IndentedTextWriter w, ModelInfo model, Names names)
    {
        var id = names.Model(model);
        var members = model.Members.AsSpan();
        var columnNames = new List<string>();
        var orders = new List<string>();
        var memberNames = new List<string>();
        foreach (var m in members)
        {
            columnNames.Add(m.ColumnName is null ? "null" : SymbolDisplay.FormatLiteral(m.ColumnName, true));
            orders.Add(m.Order.ToString(CultureInfo.InvariantCulture));
            memberNames.Add(SymbolDisplay.FormatLiteral(m.Name, true));
        }

        w.WriteLine();
        w.WriteLine(GeneratedCodeAttribute);
        w.WriteLine($"private static readonly string?[] __names_{id} = {{ {string.Join(", ", columnNames)} }};");
        w.WriteLine(GeneratedCodeAttribute);
        w.WriteLine($"private static readonly int[] __orders_{id} = {{ {string.Join(", ", orders)} }};");
        w.WriteLine(GeneratedCodeAttribute);
        w.WriteLine($"private static readonly string[] __members_{id} = {{ {string.Join(", ", memberNames)} }};");
        w.WriteLine();
        w.WriteLine(GeneratedCodeAttribute);
        w.WriteLine($"private static bool __TryBind_{id}(global::CsvMole.CsvReader r, global::CsvMole.CsvColumnMap map, out {model.TypeFullName} model)");
        w.WriteLine("{");
        w.Indent++;
        w.WriteLine("var __options = r.Options;");
        w.WriteLine("var __culture = __options.Culture;");
        w.WriteLine("var __indexes = map.Indexes;");
        for (var i = 0; i < members.Length; i++) EmitField(w, members[i], i, names);

        var args = new List<string>();
        var inits = new List<string>();
        for (var i = 0; i < members.Length; i++)
        {
            var m = members[i];
            if (m.Assignment == MemberAssignment.Constructor)
            {
                // Named arguments so unmapped optional parameters can be left out (ruling P).
                args.Add($"{Identifier(model.Constructor.ParameterNames[m.CtorParameterIndex])}: __v{i}");
                // A required member is still set in the initializer unless the ctor has [SetsRequiredMembers] (ruling Q).
                if (!m.IsRequired || model.Constructor.SetsRequiredMembers) continue;
            }
            inits.Add($"{Identifier(m.Name)} = __v{i}");
        }
        w.WriteLine(inits.Count == 0
            ? $"model = new {model.TypeFullName}({string.Join(", ", args)});"
            : $"model = new {model.TypeFullName}({string.Join(", ", args)}) {{ {string.Join(", ", inits)} }};");
        w.WriteLine("return true;");
        CloseBlock(w);
    }

    // Parses member i into the local __v{i}; on failure reports through the error policy and returns false.
    private static void EmitField(IndentedTextWriter w, MemberInfo m, int i, Names names)
    {
        var v = $"__v{i}";
        w.WriteLine($"{m.TypeFullName} {v};");
        w.WriteLine("{");
        w.Indent++;
        w.WriteLine($"var __i = __indexes[{i}];");
        w.WriteLine("if (__i >= r.FieldCount)");
        w.WriteLine("{");
        w.Indent++;
        if (m.IsNullable || m.Kind == ParseKind.NullableString) w.WriteLine($"{v} = null;");
        else EmitReport(w, m, i, "TooFewColumns", "null");
        CloseBlock(w);
        w.WriteLine("else");
        w.WriteLine("{");
        w.Indent++;
        w.WriteLine("var __f = r[__i];");

        switch (m.Kind)
        {
            case ParseKind.String:
                w.WriteLine($"{v} = __f.ToString();");
                break;
            case ParseKind.NullableString:
                w.WriteLine($"{v} = __f.IsEmpty ? null : __f.ToString();");
                break;
            default:
                var parse = m.Kind switch
                {
                    ParseKind.Enum => $"global::System.Enum.TryParse<{m.UnderlyingTypeFullName}>(__f, true, out var __p)",
                    // Same results as float/double.TryParse, with a faster path for plain decimals.
                    ParseKind.SpanParsable when m.UnderlyingTypeFullName == "float" => "global::CsvMole.CsvNumberParser.TryParseSingle(__f, __culture, out var __p)",
                    ParseKind.SpanParsable when m.UnderlyingTypeFullName == "double" => "global::CsvMole.CsvNumberParser.TryParseDouble(__f, __culture, out var __p)",
                    ParseKind.SpanParsable => $"__TryParse<{m.UnderlyingTypeFullName}>(__f, __culture, out var __p)",
                    _ => $"{names.Converter(m.ConverterTypeFullName!)}.TryParse(__f, __culture, out var __p)",
                };
                if (parse.StartsWith("__TryParse", global::System.StringComparison.Ordinal)) names.UsesSpanParsable = true;
                // A converter decides for itself what an empty field means.
                var emptyIsNull = m.IsNullable && m.Kind != ParseKind.Converter;
                if (emptyIsNull) w.WriteLine($"if (__f.IsEmpty) {v} = null;");
                w.WriteLine($"{(emptyIsNull ? "else " : "")}if ({parse}) {v} = __p;");
                w.WriteLine("else");
                w.WriteLine("{");
                w.Indent++;
                EmitReport(w, m, i, "ParseFailed", "global::CsvMole.CsvErrors.Truncate(__f)");
                CloseBlock(w);
                break;
        }
        CloseBlock(w);
        CloseBlock(w);
    }

    private static void EmitReport(IndentedTextWriter w, MemberInfo m, int i, string reason, string raw)
    {
        w.WriteLine($"global::CsvMole.CsvErrors.Report(__options, new global::CsvMole.CsvError(r.LineNumber, __i, map.HeaderNames[{i}], {SymbolDisplay.FormatLiteral(m.Name, true)}, {raw}, global::CsvMole.CsvErrorReason.{reason}));");
        w.WriteLine("model = default!;");
        w.WriteLine("return false;");
    }

    // A constrained generic call, so explicitly implemented ISpanParsable<T> (e.g. char, bool) works too; no boxing.
    private static void EmitSpanParsableHelper(IndentedTextWriter w)
    {
        w.WriteLine();
        w.WriteLine(GeneratedCodeAttribute);
        w.WriteLine("private static bool __TryParse<T>(global::System.ReadOnlySpan<char> s, global::System.IFormatProvider p, out T v) where T : global::System.ISpanParsable<T> => T.TryParse(s, p, out v!);");
    }

    private static string Identifier(string name) =>
        SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? "@" + name : name;

    private static string Sanitise(string fullName)
    {
        var chars = fullName.Replace("global::", "").ToCharArray();
        for (var i = 0; i < chars.Length; i++) if (!char.IsLetterOrDigit(chars[i])) chars[i] = '_';
        return new string(chars);
    }

    private static void OpenType(IndentedTextWriter writer, string accessibility, string keyword, string name)
    {
        writer.WriteLine(accessibility.Length == 0 ? $"partial {keyword} {name}" : $"{accessibility} partial {keyword} {name}");
        writer.WriteLine("{");
        writer.Indent++;
    }

    private static void CloseBlock(IndentedTextWriter writer)
    {
        writer.Indent--;
        writer.WriteLine("}");
    }

    /// <summary>Collision-free identifiers for one parser class's models and converters, in first-use order.</summary>
    private sealed class Names
    {
        private readonly Dictionary<string, string> _ids = new();
        private readonly HashSet<string> _used = new();
        public readonly List<ModelInfo> Models = new();
        public readonly List<string> Converters = new();
        public bool UsesSpanParsable;

        public string Model(ModelInfo model)
        {
            if (_ids.TryGetValue("m:" + model.TypeFullName, out var id)) return id;
            Models.Add(model);
            foreach (var m in model.Members)
            {
                if (m.ConverterTypeFullName is { } c && !_ids.ContainsKey("c:" + c))
                {
                    Converters.Add(c);
                    Converter(c);
                }
            }
            return Unique("m:" + model.TypeFullName, Sanitise(model.TypeFullName));
        }

        public string Converter(string fullName) =>
            _ids.TryGetValue("c:" + fullName, out var id) ? id : Unique("c:" + fullName, "__conv_" + Sanitise(fullName));

        // Sanitising can map two names to one (A.B_C / A_B.C), so a clash gets a numeric suffix.
        private string Unique(string key, string baseName)
        {
            var id = baseName;
            for (var n = 2; !_used.Add(id); n++) id = baseName + "_" + n;
            _ids[key] = id;
            return id;
        }
    }
}
